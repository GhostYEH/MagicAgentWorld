import { expect, test } from '@playwright/test';
import { ready, state, seedProgress } from './game';

test('连续世界：移动、暂停、背包与跨区域寻路', async ({page}) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await seedProgress(page,['C1','C2','C3']);
  await ready(page);
  const before = await state(page);
  await page.keyboard.down('d');
  await expect.poll(async () => (await state(page)).x).toBeGreaterThan(before.x + 20);
  await page.keyboard.up('d');
  await page.keyboard.press('Escape');
  await expect(page.locator('#game')).toHaveAttribute('data-modal', 'pause');
  const paused = await state(page);
  await page.keyboard.down('d');
  await page.waitForTimeout(400);
  await page.keyboard.up('d');
  expect((await state(page)).x).toBe(paused.x);
  await page.keyboard.press('Escape');
  await page.keyboard.press('i');
  await expect(page.locator('#game')).toHaveAttribute('data-modal', 'inventory');
  await page.keyboard.press('Escape');
  await page.keyboard.press('m');
  await expect.poll(async () => (await state(page)).atlas).toBe(true);
  await page.screenshot({path:'screenshots/game-atlas.png'});
  const destination = (await state(page)).regions.find(r => r.id === 'control-gate')!.label;
  const departure = await state(page);
  await page.mouse.click(destination.x, destination.y);
  await expect.poll(async () => (await state(page)).atlas).toBe(false);
  await expect.poll(async () => (await state(page)).navigation?.name).toBe('运行控制塔');
  const justStarted = await state(page);
  expect(Math.hypot(justStarted.x-departure.x, justStarted.y-departure.y)).toBeLessThan(250);
  await expect(page.locator('#game')).toHaveAttribute('data-modal', 'department');
  const arrived = await state(page);
  expect(arrived.region).toBe('运行控制塔');
  expect(arrived.visited).toBeGreaterThanOrEqual(2);
  expect(arrived.render.zoom).toBeLessThanOrEqual(arrived.render.maxZoom);
  expect(arrived.render.coreBuildings.every(b=>b.x>=315&&b.x+b.width<=page.viewportSize()!.width-24)).toBe(true);
  await page.screenshot({path:'screenshots/game-world-control.png'});
  await page.keyboard.press('Escape');
  await page.keyboard.press('m');
  await page.keyboard.press('Escape');
  await expect(page.locator('#game')).toHaveAttribute('data-modal', 'pause');
  page.once('dialog', dialog => dialog.accept());
  await page.mouse.click(683, (768 - 377) / 2 + 280);
  await expect.poll(async () => (await state(page)).atlas).toBe(false);
  expect((await state(page)).collected).toBe(0);
  const restarted = await state(page);
  await page.keyboard.down('d');
  await expect.poll(async () => (await state(page)).x).toBeGreaterThan(restarted.x+20);
  await page.keyboard.up('d');
  expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight)).toBe(true);
  expect(errors).toEqual([]);
});
